#!/usr/bin/env python3
"""Build Research Writer's single-file instructions using Python's standard library."""
import argparse
import hashlib
import posixpath
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "research-writer"
OUTPUT = ROOT / "portable" / "research-writer.md"


def anchor(path):
    return "resource-" + re.sub(r"[^a-z0-9]+", "-", path.lower()).strip("-")


def build():
    paths = [SKILL / "SKILL.md"]
    for folder in ("references", "templates"):
        paths.extend(sorted((SKILL / folder).rglob("*.md")))
    resources = {p.relative_to(SKILL).as_posix(): p.read_bytes() for p in paths}
    anchors = {name: anchor(name) for name in resources}
    if len(set(anchors.values())) != len(anchors):
        raise ValueError("Resource anchors collide")
    digest = hashlib.sha256()
    for name, data in resources.items():
        digest.update(name.encode("utf-8") + b"\0" + data + b"\0")

    parts = ["""# Research Writer — portable instructions

Use the included research-and-writing workflow with your task. It asks for the
finished work and delivery destination when either is unspecified. Research,
file creation and external delivery depend on the tools and access actually
available; do not claim work or access that did not occur. Skill Forge is not
required to use these instructions.

Generated by `scripts/build_portable.py` from the canonical skill and its
reference/template files. Edit those sources and regenerate this file.

Source SHA-256: `{digest}`
""".format(digest=digest.hexdigest()).rstrip()]

    for name, data in resources.items():
        def replace_link(match):
            target = match.group(2)
            if target.startswith(("#", "/")) or re.match(r"[A-Za-z][A-Za-z0-9+.-]*:", target):
                return match.group(0)
            # This package uses plain relative Markdown file links, without titles.
            if "#" in target or " " in target:
                raise ValueError("Unsupported relative link in " + name + ": " + target)
            resolved = posixpath.normpath(posixpath.join(posixpath.dirname(name), target))
            if resolved not in anchors:
                raise ValueError("Missing bundled resource: " + resolved)
            return match.group(1) + "(#" + anchors[resolved] + ")"

        body = re.sub(r"(\[[^\]]*\])\(([^)]+)\)", replace_link, data.decode("utf-8")).rstrip()
        parts.append('<a id="' + anchors[name] + '"></a>\n\n## Included resource: ' + name + "\n\n" + body)
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the committed bundle without writing")
    args = parser.parse_args()
    content = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Portable instructions are stale; run scripts/build_portable.py.\n")
        print("Portable instructions match all canonical resources.")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8")
        print("Built portable/research-writer.md")


if __name__ == "__main__":
    main()
